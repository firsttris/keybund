//! Keybund desktop app. All logic lives in `keybund-core`; this crate only
//! exposes it to the frontend as typed Tauri commands.

pub mod api;
pub mod commands;
pub mod upload;

/// All commands, for a given runtime. Expects `commands::*` in scope; used
/// by [`specta_builder`] and by the IPC tests with the mock runtime.
#[macro_export]
macro_rules! keybund_commands {
    ($r:path) => {
        tauri_specta::collect_commands![
            load_profiles,
            profile_defaults,
            normalize_folder,
            preview_new_project,
            create_project::<$r>,
            update_profile,
            set_default_profile,
            preview_add_host,
            add_host,
            copy_public_key::<$r>,
            open_url,
            test_connection,
            install_key,
            upload_target,
            upload_key,
            forget_token,
            start_device_flow,
            poll_device_flow,
            cancel_device_flow,
            last_test,
            plan_changes,
            apply_changes,
            which,
            run_doctor,
            fix_doctor,
            scan_keys,
            clone_preview,
            clone_repo,
            archive_profile,
            generated_config,
            import_proposals,
            import_profiles,
            cleanup_preview,
            cleanup_apply,
            uninstall_preview,
            uninstall_apply,
            paths,
            settings,
            update_settings,
        ]
    };
}

/// The command registry, shared by the app and the bindings export.
pub fn specta_builder() -> tauri_specta::Builder<tauri::Wry> {
    use commands::*;
    tauri_specta::Builder::<tauri::Wry>::new().commands(keybund_commands!(tauri::Wry))
}

/// Writes `src/lib/bindings.ts` for the frontend.
pub fn export_bindings(path: &std::path::Path) -> Result<(), String> {
    specta_builder()
        .export(
            specta_typescript::Typescript::default()
                .header("// @ts-nocheck\n// Generated by tauri-specta. Do not edit; run `just bindings`."),
            path,
        )
        .map_err(|e| e.to_string())
}

#[cfg_attr(mobile, tauri::mobile_entry_point)]
pub fn run() {
    let env = keybund_core::Env::from_system().expect("HOME must be set");
    let builder = specta_builder();

    tauri::Builder::default()
        .plugin(tauri_plugin_clipboard_manager::init())
        .plugin(tauri_plugin_dialog::init())
        .manage(commands::AppState::new(env))
        .invoke_handler(builder.invoke_handler())
        .setup(move |app| {
            builder.mount_events(app);
            Ok(())
        })
        .run(tauri::generate_context!())
        .expect("error while running Keybund");
}
